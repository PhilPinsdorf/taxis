import type { MaterialInput, Port } from './schemas';

const port = (id: string, name: string, connector: string, direction: Port['direction'], count = 1, required = false): Port => ({
  id,
  name,
  connector,
  direction,
  count,
  required,
});

const item = (m: Partial<MaterialInput> & Pick<MaterialInput, 'name' | 'category'>): MaterialInput => ({
  kind: 'item',
  color: '#64748b',
  width: 1,
  depth: 1,
  shape: 'rect',
  resizable: false,
  stockMode: 'unlimited',
  stockQty: 0,
  segmentLength: null,
  connector: null,
  channels: null,
  stockLengths: [],
  ports: [],
  notes: '',
  archived: false,
  ...m,
});

const cable = (name: string, connector: string, color: string, lengths: [number, number][], channels: number | null = null): MaterialInput =>
  item({
    name,
    category: 'Kabel',
    kind: 'cable',
    color,
    width: 0.05,
    depth: 0.05,
    connector,
    channels,
    stockLengths: lengths.map(([length, qty]) => ({ length, qty })),
  });

